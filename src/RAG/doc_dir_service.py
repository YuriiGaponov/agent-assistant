"""src.RAG.doc_dir_service

Модуль, реализующий логику работы с документами для Agent‑Assistant.
Содержит функции для проверки директории, чтения файлов, разбиения
на чанки и добавления документов в хранилище. Используется в рамках
RAG‑цикла для подготовки контекста для ИИ‑агента.
"""

from pathlib import Path

from src.config import Config


def doc_dir_exist(config: Config) -> bool:
    """Проверяет, является ли DOC_DIR существующей директорией.

    Возвращает True, если config.DOC_DIR — валидная директория,
    иначе — False. Не выбрасывает исключение: ответственность
    за обработку результата лежит на вызывающем коде. Применяется
    как предварительная проверка перед операциями с файлами.
    """
    return config.DOC_DIR.is_dir()


def get_doc_files(config: Config) -> list[Path]:
    """Возвращает список файлов из директории документов.

    Итерирует содержимое config.DOC_DIR и собирает все элементы
    в список объектов Path. На текущем этапе возвращает все записи
    (включая поддиректории); в дальнейшем может быть доработана
    для фильтрации по расширениям и исключения вложенных папок.
    """
    files = config.DOC_DIR.iterdir()
    return [file for file in files]
