"""src.RAG.chunking_service

Модуль, реализующий логику разбивки текста на смысловые чанки
для RAG‑конвейера Agent‑Assistant. На текущем этапе поддерживает
разбиение по абзацам; в дальнейшем может быть расширен стратегиями
фиксированного размера, перекрывающихся окон и семантической сегментации.
"""

import asyncio


def get_chunks(content: str) -> list[str]:
    """Разбивает текст на чанки по абзацам.

    Текст делится по двойным переносам строк (\n\n). Пустые блоки
    и чанки, состоящие только из пробельных символов, отфильтровываются.
    Каждый чанк очищается от ведущих и замыкающих пробелов.

    Args:
        content: Исходный текст документа.

    Returns:
        Список чанков — смысловых блоков текста. Если входной текст
        пустой или состоит только из пробелов/переносов, возвращается
        пустой список.
    """
    return [chunk.strip() for chunk in content.split("\n\n") if chunk.strip()]


async def get_chunks_async(content: str) -> list[str]:
    """Асинхронная обёртка для разбивки текста на чанки.

    Выполняет синхронную функцию get_chunks в отдельном потоке через
    run_in_executor, чтобы не блокировать event loop. Полезно при
    интеграции в асинхронный конвейер, где все операции представлены
    в едином async‑интерфейсе.

    Args:
        content: Исходный текст документа.

    Returns:
        Список чанков — смысловых блоков текста.
    """
    loop = asyncio.get_running_loop()
    return await loop.run_in_executor(None, get_chunks, content)
